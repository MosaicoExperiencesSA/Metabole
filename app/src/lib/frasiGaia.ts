/**
 * La frase di oggi per questa cliente. Stabile per tutto il giorno, diversa da cliente a
 * cliente, senza ripetizioni per 360 giorni.
 */
export function fraseDelGiorno(userId: string | null | undefined, now: Date = new Date()): string {
  // Giorni interi, contati sul calendario LOCALE del telefono: la frase cambia a mezzanotte
  // vera, ovunque sia la cliente. `Date.UTC` su anno/mese/giorno locali restituisce un multiplo
  // esatto di 86.400.000, quindi il conteggio non dipende dal fuso orario. (Provato: anche la
  // formulazione ingenua reggerebbe i cambi di ora legale — questa però dice cosa vogliamo
  // senza lasciare il dubbio a chi legge.)
  const giorno = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86_400_000);
  const h = hash32(userId || 'ospite');
  const passo = PASSI[h % PASSI.length]; // bit bassi
  const partenza = (h >>> 5) % FRASI_GAIA.length; // bit alti: indipendente dal passo
  return FRASI_GAIA[(partenza + giorno * passo) % FRASI_GAIA.length];
}
